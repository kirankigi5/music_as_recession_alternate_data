#!/usr/bin/env python3
"""Export Billboard songs lacking lyric text or awaiting lyric/recording review.

Run from the root of music_as_recession_alternate_data:
    python ~/Downloads/export_missing_song_links.py

Input files are generated by your existing LRCLIB / NetEase recovery scripts.
No requests or downloads are made. This script never opens raw lyrics text.
"""
from __future__ import annotations

import csv
import sys
from collections import Counter
from pathlib import Path
from urllib.parse import urlencode, quote_plus

csv.field_size_limit(sys.maxsize)
ROOT = Path.cwd()
REPORTS = ROOT / "reports"


def read_csv(filename, mandatory=True):
    path = REPORTS / filename
    if not path.is_file():
        if mandatory:
            raise SystemExit(f"Missing: {path}\nRun this script from your project's root folder.")
        return []
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def key(song, artist):
    return (str(song or "").strip().casefold(), str(artist or "").strip().casefold())


def lookup(rows, artist_col):
    result = {}
    for r in rows:
        result[key(r.get("song"), r.get(artist_col))] = r
    return result


lrclib = lookup(read_csv("lyrics_api_recovery.csv"), "billboard_artist")
netease = lookup(read_csv("lyrics_netease_recovery.csv"), "billboard_artist")
audit = lookup(read_csv("lyrics_combined_audit.csv"), "billboard_artist")
triage = lookup(read_csv("lyrics_quality_triage.csv"), "billboard_artist")

if not lrclib:
    raise SystemExit("The LRCLIB report is empty. Nothing to export.")

rows = []
for k, l in lrclib.items():
    n = netease.get(k, {})
    a = audit.get(k, {})
    q = triage.get(k, {})
    lst = l.get("status", "")
    nst = n.get("status", "")
    ast = a.get("audit_category", "")
    qst = q.get("quality_status", "")

    if lst in ("no_candidate", "error") and nst != "candidate_review_required":
        category = "missing_lyric_text"
    elif lst == "instrumental_review_required":
        category = "instrumental_or_no_vocals_review"
    elif ast == "high_risk":
        category = "high_risk_recording_match"
    elif ast == "needs_review":
        category = "recording_match_needs_review"
    elif qst == "review":
        category = "short_text_or_instrumental_review"
    elif ast == "promising" and qst == "preliminary_pass":
        continue  # Preliminary pass, not verified. Excluded from unresolved queue.
    else:
        category = "unclassified_review_needed"

    song = l.get("song", "")
    artist = l.get("billboard_artist", "")
    query = f'"{song}" "{artist}" lyrics'
    mbquery = f'recording:"{song}" AND artist:"{artist}"'
    provider = a.get("provider") or ("NetEase" if nst == "candidate_review_required" else "LRCLIB" if lst in ("metadata_match_provisional", "recording_review_required", "instrumental_review_required") else "")
    matched_title = a.get("matched_title") or (n.get("matched_title") if provider == "NetEase" else l.get("source_title")) or ""
    matched_artist = a.get("matched_artist") or (n.get("matched_artist") if provider == "NetEase" else l.get("source_artist")) or ""
    link_lrclib = ""
    if l.get("lrclib_id"):
        link_lrclib = f'https://lrclib.net/api/get/{quote_plus(l["lrclib_id"])}'
    link_netease = ""
    if n.get("netease_id"):
        link_netease = f'https://music.163.com/#/song?id={quote_plus(n["netease_id"])}'
    rows.append({
        "song": song,
        "billboard_artist": artist,
        "coverage_period": "1973-2023",
        "billboard_popularity_weight": l.get("weight", ""),
        "missing_or_review_status": category,
        "lrclib_status": lst,
        "netease_status": nst,
        "audit_category": ast,
        "audit_reasons": a.get("audit_reasons", ""),
        "quality_flags": q.get("quality_flags", ""),
        "candidate_provider": provider,
        "candidate_title": matched_title,
        "candidate_artist": matched_artist,
        "candidate_local_file": a.get("local_path", "") or (n.get("local_path") if provider == "NetEase" else l.get("local_json_path")) or "",
        "google_lyrics_search": "https://www.google.com/search?" + urlencode({"q": query}),
        "genius_search": "https://genius.com/search?" + urlencode({"q": song + " " + artist}),
        "musicbrainz_recording_search": "https://musicbrainz.org/search?" + urlencode({"query": mbquery, "type": "recording", "method": "indexed"}),
        "youtube_search": "https://www.youtube.com/results?" + urlencode({"search_query": song + " " + artist + " official audio"}),
        "lrclib_search_api": "https://lrclib.net/api/search?" + urlencode({"track_name": song, "artist_name": artist}),
        "lrclib_candidate_api_url": link_lrclib,
        "netease_candidate_page": link_netease,
        "review_notes": "",
    })

# Popularity weight is the same weighted chart exposure metric in the recovery pipeline.
rows.sort(key=lambda r: (-int(r["billboard_popularity_weight"] or 0), r["song"].casefold(), r["billboard_artist"].casefold()))

out = REPORTS / "missing_song_links_1973_2023.csv"
with out.open("w", encoding="utf-8-sig", newline="") as file:
    writer = csv.DictWriter(file, fieldnames=list(rows[0]))
    writer.writeheader()
    writer.writerows(rows)

print(f"Created: {out}")
print(f"Total still missing OR needing review: {len(rows)}")
for category, count in sorted(Counter(r["missing_or_review_status"] for r in rows).items()):
    print(f"  {category}: {count}")
print("Links are SEARCH pages (not verified lyrics URLs). Provider candidate URLs, when available, are listed separately.")
print("Scope: the 1,232-song LRCLIB queue for 1973–2023, not the separate 12 audit exceptions or 1959–1972.")
