"""End-to-end Model A vs Model B integration test on SYNTHETIC data.

SCOPE WARNING. Every number produced here comes from invented economic series,
invented recession labels and invented emotion scores generated by a seeded RNG.
These are SOFTWARE TESTS of the pipeline's mechanics, NOT research findings, and
they say nothing whatever about whether music predicts recessions.

No real lyrics are read. No provisional OSF candidate is treated as approved: the
one eligibility-gated call below uses a fabricated evidence row to exercise the
interface, and does not alter or relax any source-use or recording-evidence rule.
GoEmotions weights are not downloaded; a deterministic mock stands in for the
pretrained scorer, which is the documented fallback when weights are absent.

Exercised: six emotion features, popularity-weighted monthly aggregation,
six-calendar-month target alignment, expanding-window Probit fitting, identical
evaluation dates for both models, training-only feature standardisation,
absence of future-data leakage, probabilities in [0, 1], Brier/ROC-AUC, and
prediction CSV plus calibration plot generation.
"""
import csv
import json
import tempfile
import unittest
from datetime import date
from pathlib import Path

import numpy as np

from music_recession.baseline import BaselineConfig, Observation
from music_recession.economic import add_months
from music_recession.emotions import cached_score, validate_scores
from music_recession.lyrics_audit import sha, write_csv
from music_recession.music_model import aggregate, evaluate, plots
from music_recession.music_preparation import EMOTIONS

MONTHS = 300                      # 1973-01 .. 1997-12; >=247 needed for one forecast
START = date(1973, 1, 1)


def synthetic_world(seed=20261018):
    """Invented spreads, emotion series and probit-generated recession labels."""
    rng = np.random.default_rng(seed)
    months = [add_months(START, i) for i in range(MONTHS)]

    # Spread: slow cycle plus noise, so it is informative but not separating.
    phase = np.linspace(0, 6 * np.pi, MONTHS)
    spread = 1.0 + 1.2 * np.sin(phase) + rng.normal(0, 0.45, MONTHS)

    # Six emotion series, each distinct and strictly inside (0, 1).
    emotions = {}
    for index, name in enumerate(EMOTIONS):
        base = 0.35 + 0.18 * np.sin(phase * (0.4 + 0.11 * index) + index)
        emotions[name] = np.clip(base + rng.normal(0, 0.05, MONTHS), 0.02, 0.98)

    # Labels from a probit model with a dominant spread effect and mild emotion
    # effects; prevalence near 15% and no separation.
    latent = (-1.05 - 0.75 * spread
              + 0.9 * (emotions['sadness'] - 0.35) + 0.7 * (emotions['fear'] - 0.35)
              - 0.6 * (emotions['joy'] - 0.35))
    from scipy.special import ndtr
    labels = (rng.random(MONTHS) < ndtr(latent)).astype(int)
    return months, spread, emotions, labels


def build_inputs(months, spread, emotions, labels):
    """Monthly preparation rows, per-song contributions and mock emotion scores.

    Each month carries TWO synthetic songs with popularity weights 60 and 40 whose
    emotion vectors straddle the intended monthly value, so a popularity-weighted
    mean recovers that value exactly while a plain mean does not. That makes the
    weighting itself testable.
    """
    prepared, contributions, scores = [], [], {}
    for i, month in enumerate(months):
        key = month.isoformat()
        prepared.append(dict(
            predictor_month=key, target_month=add_months(month, 6).isoformat(),
            spread_t=float(spread[i]), target_t=int(labels[i]),
            total_weight=110, known_weight=105, nlp_ready_weight=100,
            provisional_weight_coverage=0.95, preparation_eligible='True'))
        for song, weight, offset in (('a', 60, 1.0), ('b', 40, -1.5)):
            song_id = f'synthetic-{i:04d}-{song}'
            reference = f'ref-{song_id}'
            vector = {}
            for name in EMOTIONS:
                delta = 0.012 * offset
                vector[name] = float(np.clip(emotions[name][i] + delta, 0.01, 0.99))
            validate_scores(vector)
            contributions.append(dict(predictor_month=key, song_id=song_id,
                                      source_reference_id=reference,
                                      nlp_ready_weight=weight, known_weight=105,
                                      total_weight=110))
            scores[song_id] = dict(metadata=dict(source_reference_id=reference),
                                   scores=vector, cache_hit=False)
    return prepared, contributions, scores


class SyntheticPipelineTests(unittest.TestCase):
    """Synthetic software validation. Not research output."""

    @classmethod
    def setUpClass(cls):
        cls.months, cls.spread, cls.emotions, cls.labels = synthetic_world()
        prepared, contributions, scores = build_inputs(cls.months, cls.spread,
                                                       cls.emotions, cls.labels)
        cls.prepared, cls.scores = prepared, scores
        cls.monthly = aggregate(prepared, contributions, scores)
        cls.economic = [Observation(m, add_months(m, 6), float(cls.spread[i]),
                                    int(cls.labels[i]))
                        for i, m in enumerate(cls.months)]
        cls.config = BaselineConfig.load(Path('config/baseline.json'))
        cls.records, cls.metrics = evaluate(cls.economic, cls.monthly, cls.config)
        cls.ok = [r for r in cls.records if r['status'] == 'ok']

    # ---------- features and aggregation ----------
    def test_six_emotion_features_present_and_valid(self):
        self.assertEqual(len(EMOTIONS), 6)
        for row in self.monthly:
            validate_scores({e: row[e] for e in EMOTIONS})

    def test_popularity_weighted_aggregation_uses_rank_weights(self):
        """60/40 weighting must recover the intended value; a plain mean must not."""
        for index in (0, 100, MONTHS - 1):
            row = self.monthly[index]
            for name in EMOTIONS:
                intended = float(np.clip(self.emotions[name][index], 0.01, 0.99))
                self.assertAlmostEqual(row[name], intended, places=9)
                plain = np.mean([np.clip(self.emotions[name][index] + 0.012, 0.01, 0.99),
                                 np.clip(self.emotions[name][index] - 0.018, 0.01, 0.99)])
                self.assertNotAlmostEqual(plain, row[name], places=6)
            self.assertEqual(row['scored_weight'], 100)
            self.assertAlmostEqual(row['scored_weight_coverage'], 100 / 110, places=12)

    def test_six_calendar_month_target_alignment(self):
        for row in self.monthly:
            predictor = date.fromisoformat(row['predictor_month'])
            self.assertEqual(row['target_month'], add_months(predictor, 6).isoformat())
        for record in self.records:
            predictor = date.fromisoformat(record['predictor_month'])
            self.assertEqual(record['target_month'], add_months(predictor, 6).isoformat())
            self.assertEqual(record['forecast_cutoff'],
                             add_months(predictor, 1).replace(day=15).isoformat())

    # ---------- paired evaluation ----------
    def test_both_models_produced_paired_forecasts(self):
        self.assertEqual(self.metrics['status'], 'complete', self.metrics['fit_failures'])
        self.assertGreater(len(self.ok), 0)
        self.assertEqual(self.metrics['evaluated_months'], len(self.ok))
        for record in self.ok:
            self.assertIsNotNone(record['model_a_probability'])
            self.assertIsNotNone(record['model_b_probability'])

    def test_identical_evaluation_dates_and_labels_for_both_models(self):
        """Pairing is the point of the comparison: same months, same labels."""
        for record in self.ok:
            self.assertIn(record['actual_label'], (0, 1))
        a_months = [r['predictor_month'] for r in self.ok if r['model_a_probability'] is not None]
        b_months = [r['predictor_month'] for r in self.ok if r['model_b_probability'] is not None]
        self.assertEqual(a_months, b_months)
        self.assertEqual(len(set(a_months)), len(a_months))

    def test_expanding_window_training_grows_and_meets_minimum(self):
        counts = [r['training_count'] for r in self.ok]
        self.assertTrue(all(c >= self.config.min_training_months for c in counts))
        self.assertEqual(counts, sorted(counts))
        self.assertGreater(counts[-1], counts[0])

    def test_no_future_data_leakage_in_any_training_window(self):
        for record in self.ok:
            predictor = date.fromisoformat(record['predictor_month'])
            latest_allowed = add_months(predictor, -self.config.training_target_lag_months)
            self.assertLessEqual(date.fromisoformat(record['training_target_end']),
                                 latest_allowed, record['predictor_month'])
            self.assertLess(date.fromisoformat(record['training_end']), predictor)
            self.assertGreaterEqual(date.fromisoformat(record['training_start']), START)

    def test_training_only_standardization(self):
        """Reported means must equal the TRAINING rows' means, excluding t onward."""
        for record in (self.ok[0], self.ok[len(self.ok) // 2], self.ok[-1]):
            report = json.loads(record['model_b_fit_json'])
            predictor = date.fromisoformat(record['predictor_month'])
            latest_allowed = add_months(predictor, -self.config.training_target_lag_months)
            training = [i for i, m in enumerate(self.months)
                        if add_months(m, 6) <= latest_allowed]
            self.assertEqual(len(training), record['training_count'])
            for name in EMOTIONS:
                expected = float(np.mean([self.monthly[i][name] for i in training]))
                self.assertAlmostEqual(report['training_mean'][name], expected, places=9)
            expected_spread = float(np.mean([self.spread[i] for i in training]))
            self.assertAlmostEqual(report['training_mean']['spread_t'], expected_spread, places=9)
            self.assertTrue(all(v > 0 for v in report['training_scale'].values()))
        first = json.loads(self.ok[0]['model_b_fit_json'])['training_mean']
        last = json.loads(self.ok[-1]['model_b_fit_json'])['training_mean']
        self.assertNotAlmostEqual(first['spread_t'], last['spread_t'], places=6)

    def test_probabilities_within_unit_interval(self):
        for record in self.ok:
            for model in ('a', 'b'):
                probability = record['model_' + model + '_probability']
                self.assertGreaterEqual(probability, 0.0)
                self.assertLessEqual(probability, 1.0)

    def test_brier_and_roc_auc_computed_for_both_models(self):
        for model in ('model_a', 'model_b'):
            block = self.metrics[model]
            self.assertIsNotNone(block)
            self.assertGreaterEqual(block['brier_score'], 0.0)
            self.assertLessEqual(block['brier_score'], 1.0)
            if block['roc_auc'] is not None:
                self.assertGreaterEqual(block['roc_auc'], 0.0)
                self.assertLessEqual(block['roc_auc'], 1.0)
            self.assertTrue(block['calibration'])
        self.assertAlmostEqual(
            self.metrics['brier_difference_b_minus_a'],
            self.metrics['model_b']['brier_score'] - self.metrics['model_a']['brier_score'],
            places=12)

    def test_brier_score_matches_manual_computation(self):
        actual = np.array([r['actual_label'] for r in self.ok], dtype=float)
        for model in ('a', 'b'):
            p = np.array([r['model_' + model + '_probability'] for r in self.ok])
            self.assertAlmostEqual(self.metrics['model_' + model]['brier_score'],
                                   float(np.mean((p - actual) ** 2)), places=12)

    # ---------- artefacts ----------
    def test_prediction_csv_calibration_csv_and_plots_are_written(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary)
            write_csv(output / 'predictions.csv', self.records)
            calibration = []
            for model in ('a', 'b'):
                calibration.extend(dict(model=model.upper(), **row)
                                   for row in self.metrics['model_' + model]['calibration'])
            write_csv(output / 'calibration.csv', calibration,
                      ['model', 'bin_lower', 'bin_upper', 'upper_inclusive', 'count',
                       'mean_predicted_probability', 'observed_recession_frequency'])
            plots(self.monthly, self.records, output)

            for name in ('predictions.csv', 'calibration.csv',
                         'lyric_coverage.png', 'probability_comparison.png'):
                path = output / name
                self.assertTrue(path.exists(), name)
                self.assertGreater(path.stat().st_size, 0, name)
            with open(output / 'predictions.csv', newline='', encoding='utf-8') as handle:
                rows = list(csv.DictReader(handle))
            self.assertEqual(len(rows), len(self.records))
            self.assertIn('model_b_probability', rows[0])


class MockEmotionInferenceTests(unittest.TestCase):
    """Validates the inference/caching interface with a deterministic mock scorer.

    GoEmotions weights are absent from this environment, so no download is
    attempted. The evidence row below is FABRICATED to exercise the gate; it does
    not approve any real candidate and changes no eligibility rule.
    """

    SENTENCES = ['invented sentence about bright mornings and open roads',
                 'invented sentence about debt letters and sleepless worry',
                 'invented sentence about a crowd shouting in the dark']

    def scorer(self, text):
        """Deterministic pseudo-scores derived from the text hash; no model."""
        digest = sha(text.encode('utf-8'))
        values = [(int(digest[i * 4:i * 4 + 4], 16) % 1000) / 1000.0 for i in range(6)]
        return dict(scores=dict(zip(EMOTIONS, values)),
                    token_count=max(1, len(text.split())), chunk_count=1)

    def eligible_row(self, text, index):
        return {'song_id': f'synthetic-{index}', 'source_reference_id': f'ref-{index}',
                'content_sha256': sha(text.encode('utf-8')), 'reviewer': 'synthetic-test',
                'recording_evidence': 'synthetic', 'language_evidence': 'synthetic',
                'permission_evidence': 'synthetic', 'release_date': '1990-01-01',
                'release_evidence': 'synthetic', 'nlp_ready': 'True',
                'recording_verified': 'True', 'language': 'en', 'source': 'osf',
                'mapping_status': 'provisional_selected', 'exclusion_reasons': '',
                'readiness_blockers': ''}

    def test_mock_inference_scores_and_caches_deterministically(self):
        config = json.loads(Path('config/music_model.json').read_text())
        with tempfile.TemporaryDirectory() as temporary:
            cache = Path(temporary) / 'emotion_cache'
            first = []
            for index, text in enumerate(self.SENTENCES):
                result = cached_score(text, self.eligible_row(text, index), config,
                                      cache, self.scorer)
                self.assertFalse(result['cache_hit'])
                validate_scores(result['scores'])
                first.append(result['scores'])
            # Identical inputs must hit the cache rather than re-infer.
            for index, text in enumerate(self.SENTENCES):
                again = cached_score(text, self.eligible_row(text, index), config,
                                     cache, self.scorer)
                self.assertTrue(again['cache_hit'])
                self.assertEqual(again['scores'], first[index])
            self.assertEqual(len(list(cache.glob('*.json'))), len(self.SENTENCES))

    def test_content_hash_mismatch_is_rejected(self):
        config = json.loads(Path('config/music_model.json').read_text())
        text = self.SENTENCES[0]
        row = self.eligible_row(text, 0)
        with tempfile.TemporaryDirectory() as temporary:
            with self.assertRaises(ValueError):
                cached_score('different text entirely', row, config,
                             Path(temporary), self.scorer)

    def test_ineligible_row_is_refused(self):
        config = json.loads(Path('config/music_model.json').read_text())
        text = self.SENTENCES[0]
        for field, value in (('recording_verified', 'False'), ('language', 'es'),
                             ('source', 'kaggle'), ('permission_evidence', '')):
            row = dict(self.eligible_row(text, 0))
            row[field] = value
            with tempfile.TemporaryDirectory() as temporary:
                with self.assertRaises(ValueError):
                    cached_score(text, row, config, Path(temporary), self.scorer)


